#!/usr/bin/env node
// Writes src/aerial-coverage.ts from the aerial overlay build's coverage.json: where each source's
// imagery is on the z13 grid, its credit, and where the overlay lifts the satellite zoom cap. The
// same file is in the archive's metadata (and so in tiles.addis.gg/aerial.json), so the map and the
// tiles it reads were cut from one plan.
//
//   node tools/aerial-coverage.mjs <coverage.json> <what it is from>
//
// <what it is from>: the archive's sha256 once it is built ("sha256 <hex>"), or the plan it was cut
// from before ("plan <date>"); written into the file's header.
import { readFileSync, writeFileSync } from "node:fs";

const [input, from] = process.argv.slice(2);
if (!input || !/^(sha256 [0-9a-f]{64}|plan \d{4}-\d{2}-\d{2})$/.test(from ?? "")) {
  console.error('usage: node tools/aerial-coverage.mjs <coverage.json> "sha256 <hex>" | "plan <yyyy-mm-dd>"');
  process.exit(2);
}
const c = JSON.parse(readFileSync(input, "utf8"));
for (const k of ["z", "sources", "cap", "full", "credits", "bounds"]) if (!(k in c)) throw new Error(`coverage.json has no ${k}`);
for (const id of Object.keys(c.sources)) if (!c.credits[id]?.en || !c.credits[id]?.fr) throw new Error(`no credit for ${id}`);
const out = `// Generated by tools/aerial-coverage.mjs from the aerial overlay build's coverage.json; do not edit.
// From: ${from} (aerial.pmtiles).
import type { OverlayCoverage } from "./coverage.ts";

export const AERIAL_COVERAGE: OverlayCoverage = ${JSON.stringify(c, null, 1)};
`;
writeFileSync(new URL("../src/aerial-coverage.ts", import.meta.url), out);
console.log(`src/aerial-coverage.ts: ${Object.keys(c.sources).length} credits, bounds ${c.bounds.join(",")}`);

#!/usr/bin/env node
// Writes what the web package compiles in from the repository's own files, so
// the package can never disagree with them:
//
//   src/generated/contracts/<id>.ts   each format-2 contract (components/<id>/<id>.contract.json), as data:
//                                one file per component, so an entry that doesn't draw a component
//                                doesn't bundle its contract (the body is "@zegadb/components/body")
//   src/generated/themes.ts      tokens/themes.json's hosts, as data
//   generated/themes.css         the same themes as CSS custom properties, for host chrome around a chart
//
//   node tools/generate.mjs           write them
//   node tools/generate.mjs --check   exit 1 if any is stale (CI; `npm run build` runs it first)
import { readFile, readdir, writeFile, mkdir, unlink } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { components } from './lib/repo.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const HEADER = '// Generated by tools/generate.mjs from the repository\'s own files. Do not edit: run `npm run generate`.\n';
const CONTRACTS_DIR = 'src/generated/contracts';

/** What is wrong on disk: each generated file that differs from its text, and each contract file no contract makes. */
export async function stale(root = ROOT) {
  const files = await generated(root);
  const out = [];
  for (const [path, text] of Object.entries(files)) {
    const current = await readFile(join(root, path), 'utf8').catch(() => null);
    if (current !== text) out.push({ path, text });
  }
  for (const name of await readdir(join(root, CONTRACTS_DIR)).catch(() => [])) {
    if (!Object.hasOwn(files, `${CONTRACTS_DIR}/${name}`)) out.push({ path: `${CONTRACTS_DIR}/${name}`, text: null });
  }
  return out;
}

/** The generated files' paths and text. */
export async function generated(root = ROOT) {
  const contracts = {};
  for (const c of await components(root)) {
    const text = await readFile(join(root, c.dir, `${c.id}.contract.json`), 'utf8').catch(() => null);
    if (!text) continue;
    const contract = JSON.parse(text);
    if (contract.format !== 2) continue;
    delete contract.$schema;
    delete contract.zql;
    contracts[c.id] = contract;
  }
  const themes = JSON.parse(await readFile(join(root, 'tokens/themes.json'), 'utf8'));
  const hosts = Object.fromEntries(Object.entries(themes.hosts).map(([id, h]) => [id, { font: h.font, light: h.light, dark: h.dark }]));
  const ts = (name, type, satisfies, value, up) => `${HEADER}import type { ${type} } from "${up}/types.ts";\n\nexport const ${name} = ${JSON.stringify(value, null, 2)} as const satisfies ${satisfies};\n`;
  const css = [
    '/* Generated by tools/generate.mjs from tokens/themes.json. Do not edit: run `npm run generate`. */',
    '/* A host puts data-zc-host="<host>" on any ancestor of a chart; data-theme="light|dark" on <html> or the system chooses the mode. */',
  ];
  const vars = (mode, font) => [
    ...Object.entries(mode).flatMap(([role, v]) => (Array.isArray(v) ? v.map((c, i) => `  --zc-${role}-${i + 1}: ${c};`) : [`  --zc-${role}: ${v};`])),
    ...(font ? Object.entries(font).map(([k, v]) => `  --zc-font-${k}: ${v};`) : []),
  ].join('\n');
  for (const [id, h] of Object.entries(hosts)) {
    css.push(`[data-zc-host="${id}"] {\n${vars(h.light, h.font)}\n}`);
    css.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) [data-zc-host="${id}"] {\n${vars(h.dark).replace(/^/gm, '  ')}\n  }\n}`);
    css.push(`:root[data-theme="dark"] [data-zc-host="${id}"] {\n${vars(h.dark)}\n}`);
  }
  return {
    ...Object.fromEntries(Object.entries(contracts).map(([id, c]) => [`${CONTRACTS_DIR}/${id}.ts`, ts('CONTRACT', 'Contract', 'Contract', c, '../..')])),
    'src/generated/themes.ts': ts('THEMES', 'HostTheme', 'Record<string, HostTheme>', hosts, '..'),
    'generated/themes.css': `${css.join('\n\n')}\n`,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const checking = process.argv.includes('--check');
  const found = await stale();
  if (checking && found.length) {
    for (const { path } of found) console.error(`${path}: stale; run \`npm run generate\` and commit the result`);
    process.exit(1);
  }
  for (const { path, text } of found) {
    if (text === null) { await unlink(join(ROOT, path)); console.log(`removed ${path}`); continue; }
    await mkdir(dirname(join(ROOT, path)), { recursive: true });
    await writeFile(join(ROOT, path), text);
    console.log(`wrote ${path}`);
  }
  if (checking) console.log(`generated files are current (${Object.keys(await generated()).length})`);
}
